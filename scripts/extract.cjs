// Extract hierarchical map: Unit -> Department -> Section -> SubSection
const hierarchy = {};

for (const item of rawData) {
  const u = (item.Unit || "").trim();
  const d = (item.Department || "").trim();
  const s = (item.Section || "").trim();
  const sub = (item.SubSection || "").trim();

  if (!u || !d) continue;

  if (!hierarchy[u]) hierarchy[u] = {};
  if (!hierarchy[u][d]) hierarchy[u][d] = {};
  if (s) {
    if (!hierarchy[u][d][s]) hierarchy[u][d][s] = new Set();
    if (sub) {
      hierarchy[u][d][s].add(sub);
    }
  }
}

// Convert to serializable structure
const result = [];
for (const [unitName, depts] of Object.entries(hierarchy)) {
  const uObj = {
    name: unitName,
    code: unitName,
    departments: []
  };
  for (const [deptName, sections] of Object.entries(depts)) {
    const dObj = {
      name: deptName,
      sections: []
    };
    for (const [secName, subSet] of Object.entries(sections)) {
      const sObj = {
        name: secName,
        subsections: Array.from(subSet).map(subName => ({ name: subName }))
      };
      dObj.sections.push(sObj);
    }
    uObj.departments.push(dObj);
  }
  result.push(uObj);
}

